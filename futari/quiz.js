function sqClean(){
  const out = [];
  for (const [i, q] of S.qz2.list.entries()) {
    const t = q.t.trim(), opts = q.o.map(o => o.trim());
    if (!t) return { err: `Q${i + 1}の問題を書いてね` };
    if (!opts[q.a]) return { err: `Q${i + 1}の「せいかい」の選択肢を書いてね` };
    const keep = opts.map((o, k) => ({ o, k })).filter(x => x.o);
    if (keep.length < 2) return { err: `Q${i + 1}は選択肢を2つ以上書いてね` };
    out.push({ t, o: keep.map(x => x.o), a: keep.findIndex(x => x.k === q.a) });
  }
  if (out.length < 3) return { err: "問題は3問以上作ってね" };
  return { q: out };
}
